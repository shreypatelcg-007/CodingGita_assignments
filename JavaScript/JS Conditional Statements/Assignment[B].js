// B] if...else Statement

// 1.
let numB1 = 7;
if (numB1 % 2 === 0) {
    console.log("Even")  // Even
} else {
    console.log("Odd")  // Odd
}

// 2.
let ageB2 = 20;
if (ageB2 >= 18) {
    console.log("Eligible")  // Eligible
} else {
    console.log("Not Eligible")  // Not Eligible
}

// 3.
let numB3 = -5;
if (numB3 >= 0) {
    console.log("Positive")  // Positive
} else {
    console.log("Negative")  // Negative
}

// 4.
let marksB4 = 72;
if (marksB4 >= 35) {
    console.log("Passed")  // Passed
} else {
    console.log("Failed")  // Failed
}

// 5.
let charB5 = "A";
if (charB5 >= "A" && charB5 <= "Z") {
    console.log("Uppercase Letter")  // Uppercase Letter
} else {
    console.log("Not an Uppercase Letter")  // Not an Uppercase Letter
}
